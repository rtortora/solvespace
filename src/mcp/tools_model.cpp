// find_faces
//-----------------------------------------------------------------------------
static double DistanceToBox(Vector p, Vector bmin, Vector bmax) {
    Vector c = Vector::From(max(bmin.x, min(p.x, bmax.x)),
                            max(bmin.y, min(p.y, bmax.y)),
                            max(bmin.z, min(p.z, bmax.z)));
    return p.Minus(c).Magnitude();
}

static void FindFaces(const json &args, ToolResult *res) {
    bool restrictGroup = args.contains("group");
    hGroup only = restrictGroup ? ParseGroup(args["group"]) : hGroup{0};
    bool byNormal = args.contains("normal");
    Vector dir = byNormal ? AxisArg(args["normal"], "normal") : Vector::From(0, 0, 0);
    bool byNear = args.contains("near");
    Vector near = byNear ? Vec3(args["near"], "near") : Vector::From(0, 0, 0);
    int limit = args.value("limit", 5);
    if(limit < 1) throw ToolError("limit must be at least 1");
    bool includeHidden = args.value("include_hidden", false);

    int activeOrder = SK.GetGroup(SS.GW.activeGroup)->order;
    struct Found { FaceInfo fi; double key; int order; };
    std::vector<Found> found;
    std::vector<hEntity> faces;
    for(Entity &e : SK.entity) {
        if(!e.IsFace()) continue;
        Group *g = SK.GetGroup(e.group);
        if(g->order > activeOrder) continue;
        if(restrictGroup && e.group != only) continue;
        faces.push_back(e.h);
    }
    for(const FaceInfo &fi : GetFaceInfos(faces)) {
        if(!fi.onSurface && !includeHidden) continue;
        if(byNormal && fi.normal.Dot(dir) < cos(10 * PI / 180)) continue;
        double key = 0;
        if(byNear) {
            key = fi.onSurface ? DistanceToBox(near, fi.bmin, fi.bmax)
                               : fabs(near.Minus(fi.point).Dot(fi.normal));
        } else {
            key = -fi.area;
        }
        found.push_back({fi, key, SK.GetGroup(fi.group)->order});
    }
    // Nearest first; otherwise the latest group's faces first, largest first.
    std::stable_sort(found.begin(), found.end(), [&](const Found &a, const Found &b) {
        if(!byNear && a.order != b.order) return a.order > b.order;
        return a.key < b.key;
    });
    json out = json::array();
    for(size_t i = 0; i < found.size() && (int)i < limit; i++) {
        json j = found[i].fi.Json();
        if(byNear) j["distance"] = Round(found[i].key);
        out.push_back(j);
    }
    res->structured = {{"faces", out}, {"matched", found.size()}};
    if(found.empty()) {
        res->structured["note"] = "No faces matched. Only faces of solids in the active "
                                  "group or earlier ones are searched; faces that were cut "
                                  "away are skipped unless include_hidden is true.";
    }
}

