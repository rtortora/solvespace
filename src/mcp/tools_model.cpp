// list_entities
//-----------------------------------------------------------------------------
static void ListEntities(const json &args, ToolResult *res) {
    hGroup hg = args.contains("group") ? ParseGroup(args["group"]) : SS.GW.activeGroup;
    bool includeAll = args.value("include_normals", false);
    bool verbose = Verbose(args);
    bool uniquePoints = args.value("unique_points", true);
    std::string kind = args.value("kind", "all");
    if(kind != "all" && kind != "curves" && kind != "points" && kind != "faces" &&
       kind != "workplanes") {
        throw ToolError("kind must be all, curves, points, faces or workplanes");
    }

    json entities = json::array();
    std::set<std::string> seenPoints;
    int duplicates = 0;
    for(Entity &e : SK.entity) {
        if(e.group != hg) continue;
        if(!includeAll && (e.IsNormal() || e.IsDistance())) continue;
        if(kind == "curves" && (e.IsPoint() || e.IsFace() || e.IsNormal() ||
                                e.IsDistance() || e.IsWorkplane())) continue;
        if(kind == "points" && !e.IsPoint()) continue;
        if(kind == "faces" && !e.IsFace()) continue;
        if(kind == "workplanes" && !e.IsWorkplane()) continue;
        if(e.IsPoint() && uniquePoints) {
            // Coincident points (line endpoints that meet, an extrusion's
            // copies of them, ...) are listed once.
            std::string key = Vec(e.PointGetNum()).dump();
            if(!seenPoints.insert(key).second) {
                duplicates++;
                continue;
            }
        }
        entities.push_back(EntityJson(&e, verbose));
    }
    json constraints = json::array();
    if(kind == "all") {
        for(Constraint &c : SK.constraint) {
            if(c.group != hg) continue;
            constraints.push_back(ConstraintJson(&c));
        }
    }
    Group *g = SK.GetGroup(hg);
    res->structured = {
        {"group", H(hg)}, {"group_name", g->name}, {"group_type", GroupTypeName(g->type)},
        {"entities", entities},
    };
    if(duplicates > 0) {
        res->structured["coincident_points_omitted"] = duplicates;
    }
    if(kind == "all") res->structured["constraints"] = constraints;
    if(hg != Group::HGROUP_REFERENCES) res->structured["solve"] = SolveStatus(hg);
}

