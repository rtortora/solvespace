static std::string Base64(const std::vector<uint8_t> &data) {
    static const char *tbl =
        "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    std::string out;
    out.reserve((data.size() + 2) / 3 * 4);
    size_t i = 0;
    for(; i + 2 < data.size(); i += 3) {
        uint32_t n = (data[i] << 16) | (data[i + 1] << 8) | data[i + 2];
        out += tbl[(n >> 18) & 63]; out += tbl[(n >> 12) & 63];
        out += tbl[(n >> 6) & 63];  out += tbl[n & 63];
    }
    if(i + 1 == data.size()) {
        uint32_t n = data[i] << 16;
        out += tbl[(n >> 18) & 63]; out += tbl[(n >> 12) & 63]; out += "==";
    } else if(i + 2 == data.size()) {
        uint32_t n = (data[i] << 16) | (data[i + 1] << 8);
        out += tbl[(n >> 18) & 63]; out += tbl[(n >> 12) & 63];
        out += tbl[(n >> 6) & 63];  out += '=';
    }
    return out;
}

std::vector<uint8_t> EncodePng(const std::shared_ptr<Pixmap> &pixmap) {
    // Pixmap only writes PNGs to files, so go through a temporary file.
    std::vector<uint8_t> png;
    FILE *tmp = tmpfile();
    if(tmp == NULL) throw ToolError("Couldn't create a temporary file for the PNG");
    bool ok = pixmap->WritePng(tmp, /*flip=*/true);
    if(ok) {
        fflush(tmp);
        long size = ftell(tmp);
        rewind(tmp);
        png.resize((size_t)size);
        ok = fread(png.data(), 1, png.size(), tmp) == png.size();
    }
    fclose(tmp);
    if(!ok) throw ToolError("Couldn't encode the screenshot as PNG");
    return png;
}

static json ImageContent(const std::vector<uint8_t> &png) {
    return {{"type", "image"}, {"mimeType", "image/png"}, {"data", Base64(png)}};
}

static json CameraJson(const Camera &camera) {
    return {{"proj_right", Vec(camera.projRight)}, {"proj_up", Vec(camera.projUp)},
            {"offset", Vec(camera.offset)}, {"scale", camera.scale}};
}

std::vector<ShotView> lastScreenshot;

// Renders the model offscreen with Cairo, from the given view preset (or
// the GUI's camera for "current"), leaving the GUI's view and display
// settings as they were.
std::shared_ptr<Pixmap> RenderOffscreen(const std::string &view, const RenderOptions &o,
                                        json *viewJson, Camera *usedCamera) {
    GraphicsWindow &gw = SS.GW;
    Vector savedOffset = gw.offset, savedRight = gw.projRight, savedUp = gw.projUp;
    double savedScale  = gw.scale;
    Unit   savedUnits  = SS.viewUnits;
    bool   savedShaded = gw.showShaded;
    GraphicsWindow::DrawOccludedAs savedOccluded = gw.drawOccludedAs;
    std::vector<GraphicsWindow::Selection> savedSelection;
    for(GraphicsWindow::Selection &s : gw.selection) savedSelection.push_back(s);
    GraphicsWindow::Selection savedHover = gw.hover;
    std::shared_ptr<BatchCanvas> savedPersistent = gw.persistentCanvas;

    if(view != "current") {
        Vector right, up;
        ViewPreset(view, &right, &up);
        gw.projRight = right;
        gw.projUp    = up;
    }
    Camera camera     = gw.GetCamera();
    camera.width      = o.width;
    camera.height     = o.height;
    camera.pixelRatio = 1;
    camera.gridFit    = true;
    if(o.zoomToFit) {
        camera.scale  = gw.ZoomToFit(camera);
        camera.offset = gw.offset;
        gw.scale      = camera.scale;
    }
    if(o.mmUnits) SS.viewUnits = Unit::MM;
    if(o.setShaded) gw.showShaded = o.shaded;
    if(o.setOccluded) gw.drawOccludedAs = o.occluded;
    gw.hover.Clear();
    gw.ClearSelection();
    for(hEntity he : o.highlight.entities) gw.MakeSelected(he);
    for(hConstraint hc : o.highlight.constraints) gw.MakeSelected(hc);

    // The GUI's persistent canvas is an OpenGL batch; it can't be drawn into
    // a Cairo surface, so draw everything directly for this frame.
    gw.persistentCanvas = NULL;

    CairoPixmapRenderer canvas;
    canvas.antialias = true;
    canvas.SetLighting(gw.GetLighting());
    canvas.SetCamera(camera);
    canvas.Init();
    canvas.StartFrame();
    gw.Draw(&canvas);
    canvas.FlushFrame();
    canvas.FinishFrame();
    std::shared_ptr<Pixmap> pixmap = canvas.ReadFrame();
    canvas.Clear();

    gw.persistentCanvas = savedPersistent;
    gw.persistentDirty  = true;
    gw.offset    = savedOffset;
    gw.scale     = savedScale;
    gw.projRight = savedRight;
    gw.projUp    = savedUp;
    SS.viewUnits = savedUnits;
    gw.showShaded = savedShaded;
    gw.drawOccludedAs = savedOccluded;
    gw.ClearSelection();
    for(GraphicsWindow::Selection &s : savedSelection) gw.MakeSelected(&s);
    gw.hover = savedHover;

    *viewJson = CameraJson(camera);
    (*viewJson)["name"] = view;
    if(usedCamera) *usedCamera = camera;
    return pixmap;
}

// Captures the next frame the GUI draws in its window.
static void ScreenshotWindow(ToolResult *res) {
    auto promise = std::make_shared<std::promise<std::vector<uint8_t>>>();
    std::shared_future<std::vector<uint8_t>> future = promise->get_future().share();
    SS.GW.onFrameCaptured = [promise](std::shared_ptr<Pixmap> pixmap) {
        try {
            promise->set_value(EncodePng(pixmap));
        } catch(...) {
            promise->set_exception(std::current_exception());
        }
    };
    SS.GW.Invalidate();
    double w, h;
    SS.GW.window->GetContentSize(&w, &h);
    double ratio = SS.GW.window->GetDevicePixelRatio();
    ShotView shot = {};
    shot.camera     = SS.GW.GetCamera();
    shot.width      = (int)(w * ratio);
    shot.height     = (int)(h * ratio);
    shot.pixelRatio = ratio;
    shot.shaded     = SS.GW.showShaded;
    lastScreenshot  = {shot};
    res->structured = {{"source", "window"},
                       {"width", (int)(w * ratio)}, {"height", (int)(h * ratio)},
                       {"view", CameraJson(SS.GW.GetCamera())}};
    res->finishOffGuiThread = [future](ToolResult *r) {
        if(future.wait_for(std::chrono::seconds(10)) != std::future_status::ready) {
            throw ToolError("The SolveSpace window wasn't redrawn within 10 s (is it "
                            "minimized or hidden?). Use source='render' instead.");
        }
        std::vector<uint8_t> png;
        try {
            png = future.get();
        } catch(std::future_error &) {
            // StopServer() dropped the capture hook.
            throw ToolError("SolveSpace's MCP server stopped before the window was "
                            "redrawn.");
        }
        r->content.push_back(ImageContent(png));
    };
}

static void Screenshot(const json &args, ToolResult *res) {
    std::string source = args.value("source", "render");
    if(source == "window") {
        for(const char *k : {"view", "views", "highlight", "shaded", "hidden_lines"}) {
            if(args.contains(k)) {
                throw ToolError(std::string(k) + " can't be used with source='window', "
                                "which shows the window exactly as it is.");
            }
        }
        if(!SS.GW.window) throw ToolError("There is no window to capture.");
        ScreenshotWindow(res);
        return;
    }
    if(source != "render") throw ToolError("source must be render or window");

    RenderOptions o = {};
    o.width  = args.value("width", 800);
    o.height = args.value("height", 600);
    if(o.width < 16 || o.width > 4096 || o.height < 16 || o.height > 4096) {
        throw ToolError("width and height must be between 16 and 4096");
    }
    std::vector<std::string> views;
    if(args.contains("views")) {
        for(const json &v : args["views"]) views.push_back(v.get<std::string>());
        if(views.empty() || views.size() > 6) throw ToolError("views needs 1 to 6 views");
    } else {
        views.push_back(args.value("view", "current"));
    }
    for(const std::string &v : views) {
        Vector r, u;
        if(v != "current") ViewPreset(v, &r, &u);   // validates
    }
    // A preset view is fitted to the model unless asked otherwise.
    bool anyPreset = false;
    for(const std::string &v : views) anyPreset = anyPreset || v != "current";
    o.zoomToFit = args.value("zoom_to_fit", anyPreset);
    std::string units = args.value("units", "mm");
    if(units != "mm" && units != "display") throw ToolError("units must be mm or display");
    o.mmUnits = (units == "mm");
    if(args.contains("shaded")) {
        o.setShaded = true;
        o.shaded = args["shaded"].get<bool>();
    }
    if(args.contains("hidden_lines")) {
        o.setOccluded = true;
        o.occluded = HiddenLinesArg(args["hidden_lines"]);
    }
    if(args.contains("highlight")) o.highlight = ParseHandles(args["highlight"]);
    for(hRequest hr : o.highlight.requests) o.highlight.entities.push_back(hr.entity(0));

    // Make sure the model is up to date before drawing it.
    Regenerate();

    json viewsJson = json::array();
    std::vector<ShotView> shots;
    for(const std::string &v : views) {
        json vj;
        ShotView shot = {};
        std::shared_ptr<Pixmap> pixmap = RenderOffscreen(v, o, &vj, &shot.camera);
        res->content.push_back(ImageContent(EncodePng(pixmap)));
        viewsJson.push_back(vj);
        shot.width      = o.width;
        shot.height     = o.height;
        shot.pixelRatio = 1;
        shot.shaded     = o.setShaded ? o.shaded : SS.GW.showShaded;
        shots.push_back(shot);
    }
    lastScreenshot = shots;
    res->structured = {{"width", o.width}, {"height", o.height},
                       {"units", units}};
    if(views.size() == 1) {
        res->structured["view"] = viewsJson[0];
    } else {
        res->structured["views"] = viewsJson;
    }
}

