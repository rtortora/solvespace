const char *ServerInstructions =
R"(This server controls a running SolveSpace instance (a parametric, constraint-based 2D/3D CAD program).

Model structure:
- A model is an ordered list of groups. Each group is either a sketch ("sketch_in_workplane", or "sketch_3d") or an operation on the group before it (extrude, lathe, revolve, helix, rotate, translate, linked). There is no editable feature history beyond this ordered group list.
- New geometry and constraints always go into the ACTIVE group. Creating a group makes it active. An extrude/lathe/revolve/helix/rotate/translate operates on the active sketch group, and is inserted after it.
- Sketch entities (lines, circles, arcs, ...) are created by "requests"; each request generates entities, e.g. a line segment request r:0004 generates the line e:00040000 and its endpoints e:00040001 and e:00040002. Handles of entities generated by operation groups (e.g. the faces and edges of an extrusion) look like e:80050012; list_entities on that group shows them.
- Geometry is positioned by a constraint solver. "dof" is the remaining degrees of freedom of a group; 0 means fully constrained. Drawing tools place geometry where you ask, but only constraints (add_constraint) keep it there.
- To start a solid: create_workplane_sketch, draw a closed profile (e.g. sketch_rectangle, sketch_circle, or sketch_line with closed=true), then extrude. To cut, extrude another profile with combine="difference".
- Sketch at a height with create_workplane_sketch {plane:"XY", offset:420}, or on a solid's face with {face: handle} (extrude returns its top/bottom faces; find_faces searches by normal or position). Pass constrain=true to sketch_rectangle / sketch_circle / sketch_line to get fully dimensioned shapes (0 DOF) in one call.
- batch runs several calls as one all-or-nothing step (e.g. sketch + profile + extrude), and can feed one call's result into the next ("$0.faces.top.handle").

Conventions:
- All lengths are in millimetres and angles in degrees, regardless of the units shown in the UI.
- In a workplane sketch, 2D coordinates [u, v] are in the workplane's frame (see u_axis/v_axis in results). The XY plane has u=X, v=Y; YZ has u=Y, v=Z; ZX has u=Z, v=X. In a 3D sketch, points are [x, y, z].
- Handles are strings: g:<hex> group, r:<hex> request, e:<hex> entity, c:<hex> constraint.
- Each modifying call is a single undo step (see undo / redo). A call that fails leaves the model unchanged.

The user's selection in the window is shared: get_selection reads it (for "this" or "what I've selected"), select sets it, and add_constraint {use_selection:true} constrains it. pick_at tells what is at a pixel of the last screenshot. measure gives volume, areas, lengths and centre of mass; check_naked_edges / check_interference validate the solid; export writes STEP, STL, SVG, DXF, PDF, PNG, ... to a path without dialogs.

Check results with get_model_summary (includes the solid's bounding box), list_entities, and visually with screenshot {views:["iso","front","right"]}, which renders without moving the user's view. Results are compact; pass verbose=true for full detail.)";

static const char *UnitName(Unit u) {
    switch(u) {
        case Unit::MM:          return "mm";
        case Unit::METERS:      return "m";
        case Unit::INCHES:      return "in";
        case Unit::FEET_INCHES: return "ft_in";
    }
    return "mm";
}

// The bounding box of the solid, as of the active group.
static bool SolidBounds(Vector *bmin, Vector *bmax) {
    Group *g = SK.GetGroup(SS.GW.activeGroup);
    g->GenerateDisplayItems();
    bool any = false;
    for(const STriangle &tr : g->displayMesh.l) {
        for(Vector p : {tr.a, tr.b, tr.c}) {
            if(!any) { *bmin = *bmax = p; any = true; }
            *bmin = Vector::From(min(bmin->x, p.x), min(bmin->y, p.y), min(bmin->z, p.z));
            *bmax = Vector::From(max(bmax->x, p.x), max(bmax->y, p.y), max(bmax->z, p.z));
        }
    }
    return any;
}

