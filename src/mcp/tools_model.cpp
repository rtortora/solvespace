static std::string Base64(const std::vector<uint8_t> &data) {
    static const char *tbl =
        "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    std::string out;
    out.reserve((data.size() + 2) / 3 * 4);
    size_t i = 0;
    for(; i + 2 < data.size(); i += 3) {
        uint32_t n = (data[i] << 16) | (data[i + 1] << 8) | data[i + 2];
        out += tbl[(n >> 18) & 63]; out += tbl[(n >> 12) & 63];
        out += tbl[(n >> 6) & 63];  out += tbl[n & 63];
    }
    if(i + 1 == data.size()) {
        uint32_t n = data[i] << 16;
        out += tbl[(n >> 18) & 63]; out += tbl[(n >> 12) & 63]; out += "==";
    } else if(i + 2 == data.size()) {
        uint32_t n = (data[i] << 16) | (data[i + 1] << 8);
        out += tbl[(n >> 18) & 63]; out += tbl[(n >> 12) & 63];
        out += tbl[(n >> 6) & 63];  out += '=';
    }
    return out;
}

static void Screenshot(const json &args, ToolResult *res) {
    int width  = args.value("width", 800);
    int height = args.value("height", 600);
    if(width < 16 || width > 4096 || height < 16 || height > 4096) {
        throw ToolError("width and height must be between 16 and 4096");
    }
    bool zoomToFit = args.value("zoom_to_fit", false);

    // Make sure the model is up to date before drawing it.
    Regenerate();

    Camera camera     = SS.GW.GetCamera();
    camera.width      = width;
    camera.height     = height;
    camera.pixelRatio = 1;
    camera.gridFit    = true;

    Vector savedOffset = SS.GW.offset;
    double savedScale  = SS.GW.scale;
    if(zoomToFit) {
        camera.scale  = SS.GW.ZoomToFit(camera);
        camera.offset = SS.GW.offset;
    }

    // The GUI's persistent canvas is an OpenGL batch; it can't be drawn into
    // a Cairo surface, so draw everything directly for this frame.
    std::shared_ptr<BatchCanvas> savedPersistent = SS.GW.persistentCanvas;
    SS.GW.persistentCanvas = NULL;

    CairoPixmapRenderer canvas;
    canvas.antialias = true;
    canvas.SetLighting(SS.GW.GetLighting());
    canvas.SetCamera(camera);
    canvas.Init();
    canvas.StartFrame();
    SS.GW.Draw(&canvas);
    canvas.FlushFrame();
    canvas.FinishFrame();
    std::shared_ptr<Pixmap> pixmap = canvas.ReadFrame();
    canvas.Clear();

    SS.GW.persistentCanvas = savedPersistent;
    SS.GW.persistentDirty  = true;
    SS.GW.offset = savedOffset;
    SS.GW.scale  = savedScale;

    // Encode to PNG via a temporary file; Pixmap only writes PNGs to files.
    std::vector<uint8_t> png;
    FILE *tmp = tmpfile();
    if(tmp == NULL) throw ToolError("Couldn't create a temporary file for the PNG");
    bool ok = pixmap->WritePng(tmp, /*flip=*/true);
    if(ok) {
        fflush(tmp);
        long size = ftell(tmp);
        rewind(tmp);
        png.resize((size_t)size);
        ok = fread(png.data(), 1, png.size(), tmp) == png.size();
    }
    fclose(tmp);
    if(!ok) throw ToolError("Couldn't encode the screenshot as PNG");

    res->content.push_back({{"type", "image"}, {"mimeType", "image/png"},
                            {"data", Base64(png)}});
    res->structured = {
        {"width", width}, {"height", height},
        {"view", {{"proj_right", Vec(camera.projRight)}, {"proj_up", Vec(camera.projUp)},
                  {"offset", Vec(camera.offset)}, {"scale", camera.scale}}},
    };
}

void AddModelTools(std::vector<Tool> *tools) {
    tools->push_back({
        "get_model_summary",
        "Summarize the open model: its groups in order (type, visibility, active "
        "flag, solve status and degrees of freedom, and operation parameters such as "
        "extrusion depth), the active group and workplane, the file name, the "
        "unsaved flag and whether undo/redo are available.",
        {{"type", "object"}, {"properties", json::object()}},
        GetModelSummary,
    });
    tools->push_back({
        "get_group",
        "Describe one group (default: the active group): type, visibility, "
        "solve status, source group, combine mode, colour, and operation "
        "parameters (depth, angle, count, step, ...).",
        {{"type", "object"}, {"properties", {
            {"group", StrProp("Group handle, e.g. 'g:0002'. Default: active group.")},
        }}},
        GetGroup,
    });
    tools->push_back({
        "list_entities",
        "List the entities and constraints of a group (default: the active group), "
        "with solved coordinates: 3D [x,y,z] and, for entities in a workplane, 2D "
        "[u,v]. Lengths in mm. Operation groups (extrude etc.) list their generated "
        "points, edges and faces; faces carry a normal and a point.",
        {{"type", "object"}, {"properties", {
            {"group", StrProp("Group handle, e.g. 'g:0002'. Default: active group.")},
            {"kind", {{"type", "string"},
                      {"enum", {"all", "curves", "points", "faces", "workplanes"}},
                      {"default", "all"},
                      {"description", "Filter entities; constraints are only listed for 'all'."}}},
            {"include_normals", BoolProp(false, "Also list normal and distance entities.")},
        }}},
        ListEntities,
    });
    tools->push_back({
        "screenshot",
        "Render the current 3D view (the same camera as the SolveSpace window) to a "
        "PNG image. Rendered offscreen, so the toolbar is not shown.",
        {{"type", "object"}, {"properties", {
            {"width",  IntProp(16, 4096, 800, "Image width in pixels.")},
            {"height", IntProp(16, 4096, 600, "Image height in pixels.")},
            {"zoom_to_fit", BoolProp(false,
                "Fit the model in the image (without moving the GUI's view).")},
        }}},
        Screenshot,
    });
}

